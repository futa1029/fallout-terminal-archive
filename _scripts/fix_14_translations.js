    if (!fs.existsSync(filePath)) {
        console.log('[Error] File not found: ' + filename);
        continue;
    }

    let html = fs.readFileSync(filePath, 'utf8');

    // 1. Title meta updates
    html = html.replace(/<title>.*?<\/title>/, "<title>" + data.name + " | Overseer Mohi's Terminal</title>");
    html = html.replace(/<meta property="og:title" content="[^"]*">/, '<meta property="og:title" content="' + data.name + ' | Overseer Mohi\'s Terminal">');

