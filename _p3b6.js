const fs = require('fs');
const dir = 'f:/Fallout/';

function update(slug, mainContent, quoteContent) {
  const fp = dir + slug + '.html';
  try {
    let html = fs.readFileSync(fp, 'utf8');
    const mainRegex = /<h2>概要<\/h2>[\s\S]*?(?=<div class="quote-box")/;
    if (!mainRegex.test(html)) { console.log('SKIP (no pattern): ' + slug); return; }
    html = html.replace(mainRegex, mainContent);
    if (quoteContent) {
      html = html.replace(/<div class="quote-box">[\s\S]*?<\/div>/, quoteContent);
    }
    fs.writeFileSync(fp, html, 'utf8');
    console.log('Updated: ' + slug);
  } catch(e) { console.log('ERROR: ' + slug + ' (' + e.message + ')'); }
}

